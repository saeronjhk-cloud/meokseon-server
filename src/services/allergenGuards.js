/**
 * allergenGuards.js — 알레르겐 토큰 경계 가드 «공통 코어» (세션54 신설)
 *
 * ── 왜 이 파일이 생겼나 ─────────────────────────────────────────────────────
 * 외부검증 회신(2026-08-06) 쟁점4: 판별기가 세 벌이고 각자 규칙을 갖는다.
 *   A  `allergenName.js`  `normalizeAllergenNames(string)`   — DB 이름 정규화
 *   B  `ocrParser.js`     `detectAllergens(text)`            — flat
 *   C  `ocrParser.js`     `detectAllergensV2(text)`          — 3분리 (화면이 쓴다)
 *
 * 세션53 이 B·C 의 «매칭 함수»(`_keywordHit`)를 합쳤다. 그러나 **경계 가드는 여전히 A 에만**
 * 있었다. 그래서 세션53 실측이 이런 상태를 만들었다:
 *   · A 는 `밀납`·`밀크씨슬`을 밀에서 제외한다.
 *   · B·C 는 그 가드를 «볼 수 없다». 그래서 세션53 은 P4(원재료표에 `밀` 단독 추가)를
 *     「가드를 B·C 에 이식한 뒤에만 하라」고 이월했다.
 * 이식(= 복사)은 세 번째 사본을 만드는 일이다. 이 저장소가 반복해서 겪은 사고가 정확히
 * 「같은 규칙이 여러 곳에 생기고 그중 하나만 고쳐지는」 것이다(세션44 `_matchSet` 반쪽 수정).
 * → 복사하지 않고 **한 곳에 두고 세 판별기가 함께 참조**한다. 그것이 이 파일이다.
 *
 * ── 계약 ───────────────────────────────────────────────────────────────────
 * `acceptAt(keyword, text, idx)` — text 의 idx 에서 시작하는 keyword 를 «그 알레르겐으로»
 *   인정할 것인가. 등록된 가드가 없으면 항상 true(= 가드는 «추가 제약»이지 허가제가 아니다).
 * `rejectAt` 은 그 부정. A 의 `NEGATIVE_GUARD` 가 「참이면 매칭하지 않는다」 계약이라 그쪽 이름을 맞췄다.
 *
 * ★ 판정은 «매칭 지점이 속한 연속 한글 토큰 전체»로 한다. 앞뒤 1글자 창이 아니다.
 *   세션50 이 실측으로 확인했듯, 뒤 1글자만 보면 `게살` ↔ `부드럽게살짝` 을 원리적으로 구분할 수 없다.
 */
'use strict';

const HANGUL = /[가-힣]/;

/** 문자열 `s` 의 위치 `idx` 가 속한 **연속 한글 토큰**의 시작 인덱스. */
function tokenStartAt(s, idx) {
  let a = idx;
  while (a > 0 && HANGUL.test(s[a - 1])) a--;
  return a;
}

/** 문자열 `s` 의 위치 `idx` 가 속한 **연속 한글 토큰**을 잘라 낸다. */
function hangulTokenAt(s, idx) {
  const a = tokenStartAt(s, idx);
  let b = idx + 1;
  while (b < s.length && HANGUL.test(s[b])) b++;
  return s.slice(a, b);
}

/** 접미 후보 중 `s` 의 끝과 맞는 «가장 긴» 것. 없으면 null. */
function endsBest(s, list) {
  let b = null;
  for (const k of list) if (s.endsWith(k) && (!b || k.length > b.length)) b = k;
  return b;
}
/** 접두 후보 중 `s` 의 앞과 맞는 «가장 긴» 것. 없으면 null. */
function startsBest(s, list) {
  let b = null;
  for (const k of list) if (s.startsWith(k) && (!b || k.length > b.length)) b = k;
  return b;
}

/* ═══════════════════════════════════════════════════════════════════════════
 * 게 — 토큰 앵커 (세션50 설계. 세션54 에 제이 결정으로 두 항목이 빠졌다)
 *
 * 문제: `게` 는 1글자다. 부사형 어미 `-게`(맛있게·풍부하게)와 외래어(스파게티·바게트)와
 *   갑각류 `게` 가 같은 글자를 쓴다. **뒤 1글자만 봐서는 원리적으로 구분되지 않는다**:
 *     게살 ↔ 부드럽게살짝 · 게장 ↔ 달콤하게장식 · 게알 ↔ 고소하게알알이
 *   해법: 매칭 지점이 속한 토큰 전체를 보고, 아래 A~E 중 하나에 «앵커된 채» 맞는지 본다.
 *   부사형 `-게` 는 언제나 토큰의 **끝**에 온다. 갑각류 `게` 는 토큰의 **머리**이거나
 *   (닫힌 목록 수식어 뒤) 또는 명사 복합어의 **꼬리**로 온다. 이 위치 차이가 유일한 구분선이다.
 *   ★ 규칙 E 의 `$` 앵커가 핵심이다. `양념게장` 은 게부위 `장` 에서 토큰이 끝나 통과하고,
 *     `부드럽게살짝` 은 `살` 뒤에 `짝` 이 더 붙어 끝나지 않으므로 거부된다.
 *
 * ★★★ 제이 결정 (2026-08-07, 세션54) — **`맛살` 과 `향` 을 CRAB_SUF 에서 뺐다.**
 *   세션50 은 이 둘을 «의도적으로» 넣고 「게맛살에 게 추출물을 넣는 제품이 실재하고,
 *   게향도 천연향 혼재 가능성을 배제할 수 없으니 안전 우선」이라고 근거를 적어 두었다.
 *   세션54 에 제이가 그 판단을 **직접 뒤집었다**:
 *     「이전에 오판이었어. 게맛살에는 게가 들어가지 않아.」  (게향도 같이 내림)
 *   근거: 게맛살은 명태 등 어육 연육 제품이고, 실측 50건의 `게향` 은 전부 「합성착향료」 표기였다.
 *   ⚠ 이것은 **세션50 결정의 폐기**다. 세션50 주석의 「오탐으로 오해해 지우지 말 것」은
 *     그 시점의 근거였고, 지금은 제이의 상위 결정으로 대체됐다. 되돌리려면 제이에게 다시 물을 것.
 *   ⚠ 부수 효과 — `게살`(진짜 게살)은 그대로 살아 있다. `살` 은 목록에 남아 있다.
 *     `게맛살` 은 `게` 다음이 `맛` 이라 규칙 B 에 걸리지 않아 거부된다. 이것이 의도한 동작이다.
 * ═══════════════════════════════════════════════════════════════════════════ */
const CRAB_SUF = '(?:살|장|알|딱지|딱|내장|육수|육|가루|분말|엑기스|엑기|엑스|추출물|추출|농축액|농축|다리|껍질|껍데기)';
const CRAB_SPECIES = '[꽃대홍털참청황]';                  // 게 종류 수식어 (닫힌 목록)
const CRAB_STATE = '(?:냉동|냉장|자숙|손질|활|생|건)';     // 게 상태 수식어 (닫힌 목록)
const CRAB_TOKEN_RULES = [
  /^게$/,                                                 // A 단독         게 · (게)
  new RegExp('^게' + CRAB_SUF),                           // B 머리+게부위   게살 · 게딱지 · 게엑기스분말
  new RegExp(CRAB_SPECIES + '게(?:$|' + CRAB_SUF + ')'),  // C 종수식어+게   홍게 · 황게 · 홍게엑기스분말
  new RegExp(CRAB_STATE + '게(?:$|' + CRAB_SUF + ')'),    // D 상태수식어+게 냉동게 · 자숙게살
  new RegExp('게' + CRAB_SUF + '$'),                      // E 복합어 꼬리   양념게장 · 냉동게살
];

/** 토큰 전체가 갑각류 「게」인가. 위치는 보지 않는다(규칙이 이미 앵커를 갖는다). */
function crabAccept(token) {
  return CRAB_TOKEN_RULES.some((re) => re.test(token));
}

