/**
 * 알레르겐 토큰 경계 가드 «공통 코어» 회귀 — 세션54 신설.
 *
 * 대상: `src/services/allergenGuards.js` 와, 그것을 쓰는 판별기 3벌.
 *   A `allergenName.js`  normalizeAllergenNames(문자열)
 *   B `ocrParser.js`     detectAllergens(텍스트)
 *   C `ocrParser.js`     detectAllergensV2(텍스트)   ← 화면이 실제로 쓴다
 *
 * ★ 이 파일이 지키는 «성질» 두 가지
 *   ① 각 가드가 양쪽 방향으로 동시에 무너지지 않는다 (과소경고 ↔ 과잉경고).
 *   ② ~~**세 판별기가 같은 답을 낸다.**~~ → ★★★ 세션58 에 **재설계**됐다. 아래를 볼 것.
 *
 * ★★★ 세션58 — 「세 판별기가 같은 답을 낸다」를 「**각 축이 자기 축에서 옳다**」로 바꿨다.
 *   무엇이 바뀌었나 (제이 결정 D55-2, 2026-08-08 · `IP/알레르기_추론폐기_설계_2026-08-08_세션55.md`):
 *     알레르기 성분은 **법정 표시란 파싱으로만** 파악한다. 원재료 형태에서 알레르겐을 «추론»하지 않는다.
 *     → `ocrParser.detectAllergens`(B) 의 `ALLERGEN_KEYWORDS` 경로와 2단계 폴백이 제거됐고,
 *       `detectAllergensV2`(C) 는 `kind==='ingredients'` 세그먼트를 아예 읽지 않는다.
 *     → **판별기 A 는 바뀌지 않았다.** A 는 HACCP `allergy` 필드·사용자 자유입력을 정규화하는
 *       별개 파이프라인이라 원재료 형태(`밀가루`→밀 · `버터`→우유)를 계속 본다.
 *
 *   ⚠ 그러므로 **A 와 B·C 가 다른 답을 내는 것이 이제 «정상»이다.** 같은 질문을 받은 것이 아니라
 *     **서로 다른 축**을 보기 때문이다. 세션54~57 의 §7 은 「A=B·C」를 단정했고, 세션58 이후 그
 *     단정은 20건이 «의도대로» 빨개진다. 그것을 그대로 두면 이 파일 전체가 무력해지므로 재설계했다.
 *
 *   ⚠ 그래서 이 파일은 이제 축마다 «다른 입력 형태»로 묻는다:
 *       A       원재료 형태 그대로            `normalizeAllergenNames('밀가루')`
 *       B·C     **법정 선언 문구**            `detectAllergens('밀 함유')`   ← `BD()`/`CD()` 어댑터
 *       B·C     원재료 문장(=아무것도 없어야)  `detectAllergens('원재료명: 밀가루')` ← `B()`/`C()` 어댑터
 *
 * ★ 뮤턴트 대응 (회신 쟁점6 — 「초록 테스트 수보다 필수 뮤턴트가 죽었는지가 중요」)
 *   MUT-BUTTER-NO-GUARD        버터 가드 제거              → §1-B 가 죽인다 (땅콩버터→우유)
 *   MUT-BUTTER-DEFAULT-REJECT  버터 기본값을 「거부」로      → §1-A 가 죽인다 (마늘버터의 우유 소실)
 *   MUT-CRAB-RESTORE-MATSAL    `맛살` 을 CRAB_SUF 에 복원   → §2-B 가 죽인다 (제이 결정 위반)
 *   MUT-CRAB-DROP-SAL          `살` 을 CRAB_SUF 에서 제거   → §2-A 가 죽인다 (게살 소실)
 *   MUT-OYSTER-NO-GUARD        굴 좌측 부정 제거            → §3 이 죽인다 (얼굴→조개류)
 *   MUT-MILKPOWDER-NO-GUARD    분유 좌측 부정 제거          → §4 가 죽인다 (전분유래→우유 + 밀 소실)
 *   MUT-SUBSTRING-DROP-MIL     `밀` 을 GUARD_DECIDES_SUBSTRING 에서 제거 → §5-A 가 죽인다
 *   MUT-SUBSTRING-ADD-GE       `게` 를 그 집합에 «추가»      → §5-B 가 죽인다 (「게를 함유」 소실)
 *   MUT-GUARD-REJECT-ERASES    가드 거부 시 텍스트를 지우도록 되돌림 → §6 이 죽인다
 *   MUT-ANY-LIST-DEAD-ENTRY    목록에 아무 일도 안 하는 항목 → §8 이 죽인다
 *   ★ 세션58 신설
 *   MUT-D55-2-REVERT           B·C 에 원재료 추론을 되살림 → §7-B 가 죽인다 (제이 결정 D55-2 위반)
 *   MUT-BC-DECL-SPLIT          B·C 의 선언 문구 판정을 갈라놓음 → §7-A 가 죽인다
 *   MUT-BC-B-EXCEEDS-C         B 가 C 에 없는 것을 냄 → §7-C 가 죽인다 (flat 이 v2 를 넘어서면 등급 없는 경고)
 *   ★ 세션58 로 «약해진» 뮤턴트 — 아래 §5-A 주석 참조
 *   MUT-SUBSTRING-DROP-MIL 은 이제 A 와 «C 의 선언 세그먼트»에서만 죽는다. B(v1)는 원재료 경로가
 *   사라져 이 규칙을 더 이상 타지 않는다.
 */
