section('§7. ★★ 세 판별기가 «같은 답» 을 낸다 (회신 쟁점4 의 존재 이유)');

// ⚠ A 와 B·C 는 구조가 다르다(A = 별칭 소비, B·C = 표 기반). 알려진 구조적 갭은 여기에만 적는다.
//   근거를 못 적는 항목은 넣지 말 것 — 넣는 순간 이 검사가 무의미해진다.
const KNOWN_DISAGREE = {
  대두밀: 'A=밀 / B·C=아님. 좌측 `대두` 를 A 는 별칭으로 «소비» 해 남은 `밀` 을 단독으로 보지만, '
    + 'B·C 의 표에는 그 소비가 없어 `대두밀` 이 미지 복합어로 남는다. '
    + '세션53 이 회신 분류 ②(제품 내부 원재료로만 확인 가능)로 «의도적으로» 남긴 갭이다. GT 4회.',
};

t('§7 같은 입력에 세 판별기의 답이 갈리지 않는다', () => {
  const CASES = [
    '밀', '밀가루', '통밀', '우리밀', '밀식이섬유', '밀쌀', '밀전분',
    '밀납', '당밀', '호밀가루', '메밀가루', '모밀가루', '밀크씨슬추출물',
    '게살', '게맛살', '게향', '홍게', '양념게장',
    '버터', '가공버터', '땅콩버터', '코코아버터',
    '분유', '탈지분유', '밀전분유래난소화성말토덱스트린',
    '굴', '굴비', '잣', '고등어', '대두밀',
  ];
  const bad = [];
  for (const s of CASES) {
    const a = A(s).join(','), b = B(s).join(','), c = C(s).join(',');
    if (b !== c) bad.push(`${s}: B=[${b}] ≠ C=[${c}]  ← B·C 는 예외 없이 같아야 한다`);
    else if (a !== b && !KNOWN_DISAGREE[s]) bad.push(`${s}: A=[${a}] ≠ B·C=[${b}]`);
  }
  assert.deepStrictEqual(bad, [],
    '판별기 간 새 불일치 — 같은 응답 안에서 값이 갈린다:\n      ' + bad.join('\n      '));
});

t('§7-B 알려진 불일치 목록이 «여전히 실재» 한다 (죽은 예외를 쌓지 않는다)', () => {
  // ⚠ 고쳐진 뒤에도 예외가 목록에 남아 있으면, 다음에 같은 결함이 재발해도 조용히 통과한다.
  const stale = Object.keys(KNOWN_DISAGREE).filter((s) => A(s).join(',') === B(s).join(','));
  assert.deepStrictEqual(stale, [],
    `해소된 예외가 목록에 남아 있다: ${stale.join(', ')} — KNOWN_DISAGREE 에서 제거할 것`);
});

