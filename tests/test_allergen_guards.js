'use strict';
const assert = require('assert');
const guards = require('../src/services/allergenGuards');
const { normalizeAllergenNames } = require('../src/services/allergenName');
const { detectAllergens, detectAllergensV2 } = require('../src/services/ocrParser');

let pass = 0;
const fails = [];
function t(title, fn) {
  try { fn(); pass++; console.log('  ✅ ' + title); }
  catch (e) { fails.push({ title, msg: e.message }); console.log('  ❌ ' + title); }
}
function section(s) { console.log('\n── ' + s + ' ' + '─'.repeat(Math.max(0, 68 - s.length))); }

// ── 판별기 3벌을 «같은 질문» 으로 부르는 어댑터 ──────────────────────────────
// ★ 세션55 — `axis()` 어댑터를 **제거했다.** 세션54 에는 A 가 `난류(가금류)`, B·C 가 `난류` 를 써서
//   여기서 한 항목을 매핑하고 있었다. 제이 결정 2026-08-08 로 B·C 를 `난류(가금류)` 로 올려
//   축이 통일됐으므로 매핑할 것이 없다.
//   ⚠ 해소된 예외는 즉시 제거한다(세션54 §10). 죽은 어댑터를 남기면 다음 사람이
//     「아직 갈려 있구나」로 읽는다 — 세션54 가 이 주석에 남긴 경고와 같은 이유다.
//   축이 다시 갈리면 `tests/test_allergen_axis.js` 가 먼저 빨간불이 된다.
const A = (s) => normalizeAllergenNames(s).map((x) => x.name).sort();
const B = (s) => detectAllergens(`원재료명: ${s}`).slice().sort();
const C = (s) => {
  const v = detectAllergensV2(`원재료명: ${s}`);
  return [...new Set([...v.contains, ...v.inferred, ...v.mayContain])].sort();
};
const hasA = (s, a) => A(s).includes(a);
const noA = (s, a) => !A(s).includes(a);

