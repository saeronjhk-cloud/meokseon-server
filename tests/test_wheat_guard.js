let pass = 0;
const fails = [];
function t(title, fn) {
  try { fn(); pass++; console.log('  ✅ ' + title); }
  catch (e) { fails.push({ title, msg: e.message }); console.log('  ❌ ' + title); }
}
function section(s) { console.log('\n── ' + s + ' ' + '─'.repeat(Math.max(0, 66 - s.length))); }

const isWheat = (s) => normalizeAllergenNames(s).some((x) => x.name === '밀');

