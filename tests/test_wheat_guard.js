section('§4. 문장 안에서도 같은 판정 (라벨 보일러플레이트)');

t('「개봉 후 밀폐 용기에 보관하십시오」 → 밀 아님', () => assert.ok(!isWheat('개봉 후 밀폐 용기에 보관하십시오')));
t('「대두, 밀 함유」 → 밀', () => assert.ok(isWheat('대두, 밀 함유')));
t('「밀납(정제) 코팅」 → 밀 아님', () => assert.ok(!isWheat('밀납(정제) 코팅')));
t('「소맥분(밀:미국산)」 → 밀', () => assert.ok(isWheat('소맥분(밀:미국산)')));

// ══════════════════════════════════════════════════════════════════════════
section('§5. ★ 규칙 결정력 감시 — 목록에 있는데 아무 일도 안 하면 「검증 완료」가 아니다');
//  외부검증 회신 쟁점1 권고: 「규칙이 있지만 실행 표본이 0이면 UNEXERCISED 여야 한다」.
//
//  ⚠ 세션53 실측으로 알게 된 것 — GT 740종에 대고 항목을 하나씩 빼 보니
//     비-밀 «접두» 21개 중 결정적인 것은 4개(당·호·오트·메)뿐이고,
//     비-밀 «접미» 15개 중에는 1개(크씨슬)뿐이었다.
//     나머지는 「모르면 거부」기본값이 이미 잡고 있어 «빼도 GT 결과가 같다».
//
//  그렇다고 목록에서 지우면 안 된다. GT 는 스냅샷이라 그 안에 없는 형태를 못 본다.
//    예) `모밀가루` 는 GT 에 없다. 그런데 `'모'` 를 빼면 R='가루' 가 밀 부위로 걸려
//        **모밀가루가 밀이 된다**(FP). ablation 은 이걸 절대 못 잡는다.
//
//  → 그래서 여기서는 GT 출현이 아니라 **「그 항목이 없었다면 판정이 뒤집혔을 입력」** 으로 잰다.
//    접두 X 에 대한 탐침은 `X + '밀가루'` 다. 밀 부위(`가루`)가 붙어 있으므로
//    X 가 목록에 없으면 반드시 밀로 인정된다. 즉 이 탐침은 X 의 결정력을 «직접» 시험한다.
//    ⚠ 탐침 문자열 중 일부는 실재하지 않는 조어다. 실물 라벨이 아니라 **규칙 시험용**이며,
//      여기에 붙은 기대값은 「이 접두가 붙으면 밀이 아니다」라는 규칙의 재진술이지
//      그 낱말이 실제로 존재한다는 주장이 아니다.

t('★ 비-밀 접두가 전부 «결정적»이다 — 하나라도 무력하면 목록에 죽은 규칙이 있는 것', () => {
  const inert = WHEAT_N_LEFT.filter((k) => isWheat(k + '밀가루'));
  assert.deepStrictEqual(inert, [],
    `무력한 접두: ${inert.join(', ')} — 이 항목들은 「X밀가루」를 막지 못한다. 규칙을 고치거나 목록에서 뺄 것`);
});

t('★ 「크씨슬」은 좌측 수식어를 이긴다 — 유일하게 결정적인 접미', () => {
  // GT ablation 상 비-밀 접미 15개 중 이것만 판정을 바꾼다(제트유기농밀크씨슬프로).
  // 나머지는 기본값 거부가 이미 잡는다 — 그 «동작» 은 §2 가 지키므로 규칙이 바뀌어도 걸린다.
  assert.ok(!isWheat('유기농밀크씨슬'), '크씨슬이 무력해졌다');
  assert.ok(!isWheat('통밀크씨슬'), '다른 수식어에서도 이겨야 한다');
});

t('밀 수식어·부위 목록이 비어 있지 않다 (MUT-WHEAT-DROP-WSUF 방어)', () => {
  assert.ok(WHEAT_PRE.length > 10 && WHEAT_SUF.length > 20, '목록이 비었다 — 밀 부위를 통째로 놓친다');
});

t('★ 밀 수식어가 전부 «결정적»이다 — 붙으면 반드시 밀로 인정돼야 한다', () => {
  // 접두 목록이 조용히 무력해지면 통밀·우리밀 같은 진짜 밀을 놓친다(과소경고).
  const inert = WHEAT_PRE.filter((k) => !isWheat(k + '밀'));
  assert.deepStrictEqual(inert, [], `무력한 밀 수식어: ${inert.join(', ')}`);
});

t('★ 밀 부위가 전부 «결정적»이다', () => {
  // 조사(을·를)는 뒤에 붙는 형태가 달라 별도로 본다.
  const skip = new Set(['을', '를']);
  const inert = WHEAT_SUF.filter((k) => !skip.has(k) && !isWheat('밀' + k));
  assert.deepStrictEqual(inert, [], `무력한 밀 부위: ${inert.join(', ')}`);
});

