section('§3. ★ 두 함정 — 서로 «반대» 방향이라 반드시 같이 본다');

t('§3-A  「통밀크래커」는 밀이다  (MUT-WHEAT-RIGHT-FIRST 를 죽인다)', () => {
  // 우측 「크」만 보고 거부하면 진짜 통밀 제품의 경고를 잃는다. allergenName.js 원 주석이
  // 가드 자체를 포기한 이유가 이것이었다. 1글자 우측 신호는 좌측 수식어를 못 이겨야 한다.
  assert.ok(isWheat('통밀크래커'), '통밀크래커의 밀을 잃었다 — 과소경고');
  assert.ok(isWheat('통밀크림빵'), '통밀크림빵의 밀을 잃었다');
});

t('§3-B  「제트유기농밀크씨슬프로」는 밀이 아니다  (MUT-WHEAT-LEFT-ALWAYS 를 죽인다)', () => {
  // 좌측 「유기농」만 보고 인정하면 milk thistle 제품이 밀이 된다(실측 FP).
  // 2글자 이상 구체 신호(「크씨슬」)는 좌측 수식어를 이겨야 한다.
  assert.ok(!isWheat('제트유기농밀크씨슬프로'), 'milk thistle 을 밀로 읽었다 — 과잉경고');
  assert.ok(!isWheat('유기농밀크씨슬'), '같은 축');
});

t('§3-C  두 함정이 같은 규칙의 «양쪽»임을 고정한다', () => {
  // 이 단정이 없으면, 규칙을 한쪽으로 밀어 놓고 반대쪽 케이스만 지우는 수정이 통과한다.
  assert.ok(isWheat('통밀크래커') && !isWheat('유기농밀크씨슬'),
    '한쪽만 성립한다 — 규칙이 한 방향으로 무너졌다');
});

